-- =============================================================================
-- Fase AB — Centro de notificaciones del panel
--
-- Contexto: la campana del panel muestra lo que pasó sin que el usuario estuviera
-- mirando: un paciente sacó o canceló un turno online, un paciente cargó sus datos
-- desde el link (Fase AA), etc. Con notificaciones sin leer, la campana muestra un
-- indicador.
--
-- Qué hace:
--   1. Tabla notificacion: una fila por destinatario (persona) y clínica. La escribe
--      solo el backend (utils/notificaciones.js) y la lee el propio destinatario.
--      `datos` lleva lo que el panel necesita para abrir el detalle (p. ej. el DNI
--      de la ficha) sin ponerlo en la URL.
--   2. RLS activada SIN políticas + REVOKE a anon/authenticated: solo service_role
--      (el backend filtra siempre por la persona y la clínica de la sesión).
--
-- Aditivo: tabla nueva, no toca datos existentes.
-- Idempotente: se puede correr más de una vez.
-- Reversión: DROP TABLE IF EXISTS notificacion;
-- =============================================================================

BEGIN;

CREATE TABLE IF NOT EXISTS notificacion (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinica_id  uuid NOT NULL REFERENCES clinica(id) ON DELETE CASCADE,
    id_persona  bigint NOT NULL REFERENCES persona(id) ON DELETE CASCADE,
    tipo        text NOT NULL CHECK (tipo IN ('turno_nuevo', 'turno_cancelado', 'datos_paciente')),
    titulo      text NOT NULL,
    cuerpo      text,
    url         text,
    datos       jsonb,
    creado_en   timestamptz NOT NULL DEFAULT now(),
    leida_en    timestamptz
);
CREATE INDEX IF NOT EXISTS idx_notificacion_destino
    ON notificacion (id_persona, clinica_id, creado_en DESC);
CREATE INDEX IF NOT EXISTS idx_notificacion_no_leidas
    ON notificacion (id_persona, clinica_id) WHERE leida_en IS NULL;

ALTER TABLE notificacion ENABLE ROW LEVEL SECURITY;
REVOKE ALL PRIVILEGES ON notificacion FROM PUBLIC, anon, authenticated;

COMMIT;
