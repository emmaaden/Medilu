-- Motivación: hasta ahora "una persona = una clínica" (persona.clinica_id 1:1) y
-- el admin era un booleano (profesional.es_admin). A partir de esta fase un mismo
-- profesional puede pertenecer a VARIAS clínicas con un ROL DISTINTO en cada una.
--
--   * `membresia` = fuente de verdad de "quién pertenece a qué clínica y con qué rol".
--   * `persona`   = identidad global del profesional (1 por id_auth). persona.clinica_id
--                   queda como legacy (clínica de origen) y se conserva por compatibilidad.
--   * La "clínica activa" de la sesión viaja como header `x-clinica-id` (lo pone el backend
--     al operar por-JWT). app_current_clinica_id() la valida contra una membresía activa.
--
