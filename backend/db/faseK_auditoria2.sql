-- C. AUTORIZACIONES PREVIAS (antes que registro_practica, que la referencia)
-- ===========================================================================
CREATE TABLE IF NOT EXISTS autorizacion (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinica_id           uuid   NOT NULL REFERENCES clinica(id) ON DELETE CASCADE,
    id_paciente          bigint NOT NULL REFERENCES paciente(id) ON DELETE CASCADE,
    id_profesional       bigint REFERENCES profesional(id) ON DELETE SET NULL,
    profesional_nombre   text,
    paciente_nombre      text,
    -- Práctica solicitada (snapshot del catálogo).
    id_practica          bigint REFERENCES practica(id) ON DELETE SET NULL,
    practica_codigo      text NOT NULL,
    practica_descripcion text NOT NULL,
    pieza                text,             -- diente/s o zona (texto libre)
    cantidad             int  NOT NULL DEFAULT 1 CHECK (cantidad BETWEEN 1 AND 99),
    diagnostico_cie10    text REFERENCES cie10(codigo),
    fundamento           text NOT NULL,
    odontograma          jsonb,            -- snapshot opcional del odontograma
    -- Cobertura al momento de pedirla (snapshot).
    id_obra_social       bigint REFERENCES obra_social(id) ON DELETE SET NULL,
    obra_social_nombre   text,
    nro_afiliado         text,
    -- Resolución de la auditoría.
    estado               text NOT NULL DEFAULT 'pendiente'
                         CHECK (estado IN ('pendiente', 'aprobada', 'rechazada', 'cancelada')),
    numero               text UNIQUE,      -- n.º de autorización (al aprobar)
    motivo               text,             -- respuesta/condiciones del auditor
    vence_en             date,
    id_persona_auditor   bigint REFERENCES persona(id) ON DELETE SET NULL,
    auditor_nombre       text,
    resuelta_en          timestamptz,
    creado_en            timestamptz NOT NULL DEFAULT now()
