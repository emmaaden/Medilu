-- Helpers del alcance: por id de catálogo (preferido) o por texto (legado).
CREATE OR REPLACE FUNCTION public.app_auditor_alcance_id()
RETURNS bigint
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
AS $$
    SELECT m.alcance_id_obra_social
    FROM membresia m
    JOIN persona pe ON pe.id = m.id_persona
    WHERE pe.id_auth = auth.uid()
      AND m.activo = true
      AND m.rol = 'auditor'
      AND m.clinica_id = public.app_current_clinica_id()
    LIMIT 1;
$$;
GRANT EXECUTE ON FUNCTION public.app_auditor_alcance_id() TO authenticated;
REVOKE EXECUTE ON FUNCTION public.app_auditor_alcance_id() FROM anon, public;

-- ¿Auditor interno (sin alcance por obra social)?
CREATE OR REPLACE FUNCTION public.app_auditor_es_interno()
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
AS $$
    SELECT public.app_auditor_alcance_id() IS NULL AND public.app_auditor_alcance() IS NULL;
$$;
GRANT EXECUTE ON FUNCTION public.app_auditor_es_interno() TO authenticated;
REVOKE EXECUTE ON FUNCTION public.app_auditor_es_interno() FROM anon, public;

CREATE OR REPLACE FUNCTION public.app_auditor_ve_paciente(p_id_paciente bigint)
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
AS $$
    SELECT CASE
        WHEN public.app_auditor_alcance_id() IS NOT NULL THEN EXISTS (
            SELECT 1 FROM paciente pa
            WHERE pa.id = p_id_paciente AND pa.id_obra_social = public.app_auditor_alcance_id()
        )
        WHEN public.app_auditor_alcance() IS NOT NULL THEN EXISTS (
            SELECT 1 FROM paciente pa
            WHERE pa.id = p_id_paciente AND lower(trim(pa.obra_social)) = public.app_auditor_alcance()
        )
        ELSE true
    END;
$$;
GRANT EXECUTE ON FUNCTION public.app_auditor_ve_paciente(bigint) TO authenticated;
REVOKE EXECUTE ON FUNCTION public.app_auditor_ve_paciente(bigint) FROM anon, public;

CREATE OR REPLACE FUNCTION public.app_auditor_ve_persona(p_id_persona bigint)
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
AS $$
    SELECT CASE
        WHEN public.app_auditor_es_interno() THEN true
        WHEN NOT EXISTS (SELECT 1 FROM paciente pa WHERE pa.id_persona = p_id_persona) THEN true
        ELSE EXISTS (
            SELECT 1 FROM paciente pa
            WHERE pa.id_persona = p_id_persona AND public.app_auditor_ve_paciente(pa.id)
        )
    END;
$$;
GRANT EXECUTE ON FUNCTION public.app_auditor_ve_persona(bigint) TO authenticated;
REVOKE EXECUTE ON FUNCTION public.app_auditor_ve_persona(bigint) FROM anon, public;

-- La bitácora usa "interno" (antes: alcance de texto IS NULL).
DROP POLICY IF EXISTS hc_acceso_select ON hc_acceso;
CREATE POLICY hc_acceso_select ON hc_acceso
    FOR SELECT TO authenticated
    USING (
        clinica_id = public.app_current_clinica_id()
        AND (
            public.app_is_clinica_admin()
            OR (
                public.app_is_clinica_auditor()
                AND (
                    public.app_auditor_es_interno()
                    OR (id_paciente IS NOT NULL AND public.app_auditor_ve_paciente(id_paciente))
                )
            )
        )
    );

