-- La asistencia la marca solo el staff (backend). El paciente puede actualizar su
-- turno por la RLS de la Fase 3 (cancelar): no debe poder marcarse "atendido".
CREATE OR REPLACE FUNCTION public.turno_proteger_asistencia()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
    IF COALESCE(auth.jwt()->>'role', 'service_role') = 'service_role' THEN
        RETURN NEW;
    END IF;
    IF NEW.estado IN ('atendido', 'ausente')
       AND NEW.estado IS DISTINCT FROM (CASE WHEN TG_OP = 'UPDATE' THEN OLD.estado END) THEN
        RAISE EXCEPTION 'La asistencia solo la registra la clínica';
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS turno_asistencia_protegida ON turno;
CREATE TRIGGER turno_asistencia_protegida
    BEFORE INSERT OR UPDATE ON turno
    FOR EACH ROW EXECUTE FUNCTION public.turno_proteger_asistencia();

