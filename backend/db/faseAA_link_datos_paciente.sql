-- Fase AA — Link para que el paciente cargue sus datos personales
--
-- Contexto: el profesional genera un link y se lo manda al paciente (WhatsApp,
-- email, copiar). El paciente lo abre SIN cuenta, completa sus datos personales
-- y su cobertura, y quedan en la ficha de la clínica.
--   - Link "nuevo": crea la ficha (persona + paciente) en la clínica. Si ya hay
--     un paciente con ese DNI en la clínica, solo completa los datos vacíos (no
--     pisa nada: el link no prueba que quien lo abre sea ese paciente).
--   - Link de un paciente existente (id_paciente): el paciente tiene que escribir
--     su DNI y tiene que coincidir con el de la ficha; los datos que carga
--     reemplazan los de la ficha (salvo DNI/email si tiene cuenta en Medilu).
--
-- Qué hace:
--   1. Tabla link_datos_paciente: un link de UN SOLO USO, con vencimiento (7 días,
--      lo pone el backend). Se guarda SOLO el hash SHA-256 del token (como
--      turno.manage_token): si se filtrara la tabla, los links no se reconstruyen.
--      Guarda también la prueba del consentimiento (versión legal + fecha).
--   2. RLS activada SIN políticas + REVOKE a anon/authenticated: solo la usa el
--      backend con service_role.
--   3. Bitácora (hc_acceso): acciones 'link_datos' (el profesional genera el link)
--      y 'datos_por_link' (el paciente carga sus datos).
--
-- Aditivo: tabla nueva, no toca datos existentes.
-- Idempotente: se puede correr más de una vez.
-- Reversión: ver el bloque comentado al final.
-- =============================================================================

BEGIN;

-- -----------------------------------------------------------------------------
-- 1. Links.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS link_datos_paciente (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash     text NOT NULL UNIQUE,
    clinica_id     uuid NOT NULL REFERENCES clinica(id) ON DELETE CASCADE,
    -- NULL = paciente nuevo; si no, la ficha a completar.
    id_paciente    bigint REFERENCES paciente(id) ON DELETE CASCADE,
    creado_por     bigint REFERENCES persona(id) ON DELETE SET NULL,
    creado_por_nombre text,
    creado_en      timestamptz NOT NULL DEFAULT now(),
    vence_en       timestamptz NOT NULL,
    usado_en       timestamptz,
    -- DNI mal escrito en un link de paciente existente: a los 5 el link se anula.
    intentos       int NOT NULL DEFAULT 0,
    -- Ficha que quedó cargada (la nueva o la existente).
    id_paciente_resultado bigint REFERENCES paciente(id) ON DELETE SET NULL,
    -- Prueba del consentimiento (Ley 25.326).
    version_legal  text,
    ip             text
);
CREATE INDEX IF NOT EXISTS idx_link_datos_clinica ON link_datos_paciente (clinica_id, creado_en DESC);

-- -----------------------------------------------------------------------------
-- 2. Solo service_role.
-- -----------------------------------------------------------------------------
ALTER TABLE link_datos_paciente ENABLE ROW LEVEL SECURITY;
REVOKE ALL PRIVILEGES ON link_datos_paciente FROM PUBLIC, anon, authenticated;

-- -----------------------------------------------------------------------------
-- 3. Bitácora: misma lista que la Fase Z + las dos nuevas.
-- -----------------------------------------------------------------------------
ALTER TABLE hc_acceso DROP CONSTRAINT IF EXISTS hc_acceso_accion_check;
ALTER TABLE hc_acceso ADD CONSTRAINT hc_acceso_accion_check CHECK (accion IN (
    'ver_hc', 'crear_registro', 'registrar_paciente',
    'exportar_hc', 'importar_hc',
    'ver_registro_auditoria', 'revisar', 'responder',
    'solicitar_autorizacion', 'ver_autorizacion', 'resolver_autorizacion',
    'ver_adjunto_autorizacion', 'editar_cobertura',
    'codigo_vinculacion', 'vincular_historia',
    'editar_datos_paciente', 'cargar_pediatria',
    'link_datos', 'datos_por_link'));

COMMIT;

